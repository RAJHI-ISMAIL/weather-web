/**
 * Filter places based on the current camera altitude (zoom level)
 * and optional category filter.
 */
export function getPlacesForZoom(
  altitude: number,
  categoryFilter: string = "all"
): GlobePlace[] {
  // When 'all' is selected, apply Google Earth Level-of-Detail (LOD) based on camera altitude.
  // When a specific category is selected, allow all places in that category to be visible for exploration.
  let maxTier: 1 | 2 | 3 | 4 = 1;
  if (categoryFilter !== "all") {
    maxTier = 4;
  } else if (altitude <= 0.95) {
    maxTier = 4;
  } else if (altitude <= 1.45) {
    maxTier = 3;
  } else if (altitude <= 2.1) {
    maxTier = 2;
  } else {
    maxTier = 1;
  }

  return GLOBE_PLACES.filter((place) => {
    // Zoom tier check
    if (place.tier > maxTier) return false;

    // Category filter check
    if (categoryFilter !== "all") {
      if (categoryFilter === "wonders") {
        return place.category === "landmark" || place.category === "nature";
      }
      return place.category === categoryFilter;
    }
    return true;
  });
}

/**
 * Helper to get a human-friendly label for current zoom level
 */
export function getZoomTierInfo(altitude: number): {
  level: number;
  name: string;
  badge: string;
  description: string;
} {
  if (altitude <= 0.95) {
    return {
      level: 4,
      name: "Landmark & Local View",
      badge: "Deep Zoom",
      description: "World wonders, iconic landmarks & natural marvels visible",
    };
  }
  if (altitude <= 1.45) {
    return {
      level: 3,
      name: "City & Destination View",
      badge: "Close Zoom",
      description: "Cultural hubs, scenic destinations & key cities visible",
    };
  }
  if (altitude <= 2.1) {
    return {
      level: 2,
      name: "Regional View",
      badge: "Medium Zoom",
      description: "Capitals & regional metropolises visible",
    };
  }
  return {
    level: 1,
    name: "Global Orbit",
    badge: "High View",
    description: "Global megacities visible • Zoom in to reveal more places",
  };
}
